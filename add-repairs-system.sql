-- 1. เพิ่มสถานะเครื่องมือ: 'normal' (ปกติ) / 'repairing' (กำลังซ่อม)
--    เมื่อเป็น 'repairing' เครื่องมือจะเบิกไม่ได้ จนกว่าแอดมินจะปิดงานซ่อม
ALTER TABLE tools
    ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'normal'
    CHECK (status IN ('normal','repairing'));

-- 2. ตารางใบแจ้งซ่อม
CREATE TABLE IF NOT EXISTS repairs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_id BIGINT NOT NULL REFERENCES tools(id) ON DELETE CASCADE,
    reported_by TEXT NOT NULL,            -- ชื่อพนักงานผู้แจ้ง
    issue TEXT NOT NULL,                  -- รายละเอียดอาการเสีย
    image_url TEXT,                       -- รูปถ่ายประกอบ (ถ้ามี)
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending','repairing','done','rejected')),
    admin_note TEXT,                      -- หมายเหตุจากแอดมิน (เช่น สาเหตุ/ค่าใช้จ่าย)
    resolved_by TEXT,                     -- ชื่อแอดมินที่ปิดงาน
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

CREATE INDEX IF NOT EXISTS repairs_tool_id_idx ON repairs(tool_id);
CREATE INDEX IF NOT EXISTS repairs_status_idx ON repairs(status);

